a=1
print(a)
#基础赋值，即a赋值为1

a+=1
print(a)
#加法赋值,即让在之前的基础上加1，得到的结果成为新的a

a-=1
print(a)
#减法赋值，即让在之前的基础上减1，得到的结果成为新的a

a/=2
print(a)
#除法赋值，在之前按的基础上除以2，得到新的结果成为a

a*=10
print(int(a))
#乘法赋值，在之前的基础上乘10，得到新的结果成为a

a//=0.2
print(int(a))
#整除赋值，在之前的基础上整除0.2，得到新的结果成为a

a**=2
print(int(a))
#幂赋值，即将之前的值变为a的2次方

a%=5
print(int(a))
#取余赋值，将之前的值整除2，得到的余数变成a的新值
#以上为算术运算符的赋值运算符变种
